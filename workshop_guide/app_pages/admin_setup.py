_USER_OK = re.compile(r"^[A-Za-z0-9_.@\-]+$")   # rejects quotes/spaces so nothing can break out of the SQL string
_EMAIL_OK = re.compile(r"^[A-Za-z0-9_.+\-]+@[A-Za-z0-9\-]+(\.[A-Za-z0-9\-]+)+$")
_EMAIL_LINE = re.compile(r"^SET LAB_ADMIN_EMAIL = '[^']*';", re.M)


def _full_setup_sql(email: str, bind_sql: str) -> tuple[str, list[str]]:
    """00 + 01 + 02 (email filled in) + the generated bind script, as one paste."""
    if not _EMAIL_OK.match(email or ""):
        return "", ["Enter a valid admin email (it must be a verified email on a Snowflake user)."]
    s00 = sql_file("00_admin_setup.sql")
    if not _EMAIL_LINE.search(s00):
        return "", ["Could not find `SET LAB_ADMIN_EMAIL = ...` in 00_admin_setup.sql - edit it by hand."]
    s00 = _EMAIL_LINE.sub(f"SET LAB_ADMIN_EMAIL = '{email}';", s00, count=1)
    banner = "-- " + "=" * 77
    parts = [f"{banner}\n-- Gladstone DQ HOL | LAB SETUP (generated): account, template, procedures, attendees\n"
             f"-- Run top to bottom in ONE Snowsight worksheet as ACCOUNTADMIN (Run All). ~2 min + ~20 s per attendee.\n{banner}"]
    for title, body in [("00_admin_setup.sql", s00), ("01_build_template.sql", sql_file("01_build_template.sql")),
                        ("02_lab_procs.sql", sql_file("02_lab_procs.sql")), ("bind attendees", bind_sql)]:
        parts.append(f"\n{banner}\n-- >>> {title}\n{banner}\n{body.strip()}\n")
    return "\n".join(parts), []


def _bind_sql(roster: pd.DataFrame, n_spares: int, set_defaults: bool = False) -> tuple[str, list[str]]:
    """Attendee + spare section of the setup script, for the roster typed into the editor."""
    problems, rows, seen = [], [], set()
    auto = 0
    for i, r in enumerate(roster.fillna("").to_dict("records"), start=1):
        user = str(r.get("Snowflake user", "")).strip()
        name = str(r.get("Operator name", "")).strip().upper()
        if not user and not name:
            continue
        if not user:
            problems.append(f"Row {i}: Snowflake user is missing.")
            continue
        if not _USER_OK.match(user):
            problems.append(f"Row {i}: `{user}` - user names may only contain letters, digits and _ . @ -")
            continue
        if not name:
            auto += 1
            name = f"OPERATOR{auto:02d}"
            while name in seen:
                auto += 1
                name = f"OPERATOR{auto:02d}"
        if not re.fullmatch(r"[A-Z0-9_]{1,20}", name) or name.startswith("SPARE"):
            problems.append(f"Row {i}: operator name `{name}` must be 1-20 letters, digits or _ and not start with SPARE.")
            continue
        if name in seen:
            problems.append(f"Row {i}: operator name `{name}` is used twice.")
            continue
        seen.add(name)
        rows.append({"user": user, "name": name, **({"set_defaults": True} if set_defaults else {})})
    if not rows:
        problems.append("Enter at least one attendee.")
    if problems:
        return "", problems

    roster_json = json.dumps(rows, indent=2)
    users_in = ", ".join(f"'{r['user'].upper()}'" for r in rows)
    first = rows[0]["name"]
    second = rows[1]["name"] if len(rows) > 1 else None
    parts = [
        "-- Gladstone DQ HOL | bind attendees to simulated operators (generated by the workshop guide)",
        "-- Run as ACCOUNTADMIN. " + ("Attendees' DEFAULT_ROLE / DEFAULT_WAREHOUSE are SET to the lab's (restored at teardown)."
                                       if set_defaults else "User defaults are NOT changed - attendees run USE ROLE themselves."),
        "USE ROLE ACCOUNTADMIN;",
        "USE WAREHOUSE DQ_LAB_WH;",
        "",
        f"-- 1. Check the users exist: expect {len(rows)} row(s); a missing user = fix the name first",
        "SHOW USERS;",
        'SELECT "name" FROM TABLE(RESULT_SCAN(LAST_QUERY_ID()))',
        f' WHERE UPPER("name") IN ({users_in});',
        "",
        "-- 2. Build CUST_<NAME> + role DQ_LAB_<NAME> and grant the role to each user (~20 s each)",
        f"CALL GLADSTONE_DQ_LAB.ADMIN.SETUP_ALL(PARSE_JSON($${roster_json}$$));",
        "",
    ]
    if n_spares:
        parts += [f"-- 3. Spares for walk-ins (claim on the day: CALL GLADSTONE_DQ_LAB.ADMIN.CLAIM_SPARE('<USER>');)",
                  f"CALL GLADSTONE_DQ_LAB.ADMIN.SETUP_SPARES({n_spares});", ""]
    parts += [
        "-- 4. Confirm everyone is ASSIGNED",
        "SELECT * FROM GLADSTONE_DQ_LAB.ADMIN.V_ROSTER;",
        "",
        f"-- 5. Smoke test as {first}",
        f"USE ROLE DQ_LAB_{first}; USE SECONDARY ROLES NONE; USE WAREHOUSE DQ_LAB_WH;",
        f"SHOW DYNAMIC TABLES IN SCHEMA GLADSTONE_DQ_LAB.CUST_{first};   -- 3, INCREMENTAL",
    ]
    if second:
        parts.append(f"SELECT COUNT(*) FROM GLADSTONE_DQ_LAB.CUST_{second}.MEMBERS__MEMBER;   -- must FAIL: not authorized")
    parts += ["USE ROLE ACCOUNTADMIN;", "", "-- Tell each attendee their operator name:"]
    parts += [f"--   {r['user']:<30} -> {r['name']}   " + ("" if set_defaults else f"(USE ROLE DQ_LAB_{r['name']};)") for r in rows]
    return "\n".join(parts), []

